// 外からアプリを開くリンク（lincrea://… や、通知・ほかのアプリからのリンク）の行き先を決める（Expo Router の決まりのファイル）。
//
// このアプリは、外からのリンクで特定の画面を開く使い方をしない。リンクに画面の名前や値を書いて開けると、
// メールやチャットのリンク1つで、勝手に画面を開いて入力させたり、ボタンを押させたりできてしまう。
// そこで、外からのリンクは中身を見ずに:
//   - アプリを起動したリンクなら、いつもの最初の画面（マイアプリ・ログイン）から始める
//   - 開いているときに来たリンクなら、いまの画面のまま何もしない
export function redirectSystemPath({ initial }: { path: string; initial: boolean }): string | null {
  return initial ? '/' : null;
}
